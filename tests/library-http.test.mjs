test('collection APIs batch local paths, report issues, adjust space budget and stay out of bootstrap and model tasks', async t => {
  const directory = await realpath(await mkdtemp(path.join(os.tmpdir(), 'secondu-collection-http-')));
  const files = path.join(directory, 'Fictional'); await mkdir(files);
  const selected = path.join(files, 'fictional.txt'); await writeFile(selected, '虚构集成：绿色风筝。');
  let pickerCalls = 0;
  const app = createApp({ dataDir: path.join(directory, 'data'), seed: false, scheduler: false, computerInfo: { codexAvailable: false }, chooseFiles: async () => { pickerCalls++; return [selected]; } });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); await rm(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${app.server.address().port}/api/spaces/personal`;
  await fetch(base, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  async function request(route, body, method = 'POST') { return fetch(base + route, { method, headers: { 'Content-Type': 'application/json' }, ...(method !== 'GET' ? { body: JSON.stringify(body ?? {}) } : {}) }); }
  assert.equal((await request('/library/choose-files', { command: 'invalid' })).status, 400); assert.equal(pickerCalls, 0);
  assert.deepEqual((await (await request('/library/choose-files')).json()).paths, [selected]);
  const rootResponse = await request('/library/collections', { name: '虚构 HTTP', mode: 'linked' }); assert.equal(rootResponse.status, 201);
  const root = await rootResponse.json();
  const added = await (await request(`/library/collections/${root.id}/files`, { paths: [selected, path.join(files, 'missing')] })).json();
  assert.equal(added.added, 1); assert.equal(added.rejected.length, 1);
  assert.equal((await (await request(`/library/collections/${root.id}/issues`, undefined, 'GET')).json()).total, 1);
  assert.equal((await (await request(`/library/collections/${root.id}`, { name: '虚构新标题' }, 'PUT')).json()).name, '虚构新标题');
  assert.equal((await request('/library/storage', { budgetGiB: 12, reserveGiB: 5 }, 'PUT')).status, 200);
  assert.equal((await (await request('/library/storage', undefined, 'GET')).json()).budgetGiB, 12);
  await request(`/library/roots/${root.id}/resume`);
  for (let i = 0; i < 100; i++) { if ((await (await request('/library/roots', undefined, 'GET')).json()).items[0]?.status !== 'running') break; await new Promise(resolve => setTimeout(resolve, 20)); }
  const found = await (await request('/library/search?query=' + encodeURIComponent('绿色风筝'), undefined, 'GET')).json(); assert.equal(found.items.length, 1);
  const boot = await (await request('/bootstrap', undefined, 'GET')).json(); assert.ok(!JSON.stringify(boot).includes('绿色风筝')); assert.equal(boot.sources.length, 0);
  const demo = base.replace('/personal', '/demo-us-v1');
  await fetch(demo, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal((await fetch(demo + '/library/choose-files', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  assert.equal(pickerCalls, 1);
});

test('folder APIs stream local media, isolate versions, and hand evidence to existing review without model execution', async t => {
  const directory = await realpath(await mkdtemp(path.join(os.tmpdir(), 'secondu-library-http-')));
  const files = path.join(directory, 'fictional'); await mkdir(files);
  await writeFile(path.join(files, 'note.md'), '虚构材料：我们周末一起看书。');
  const wave = Buffer.alloc(48); wave.write('RIFF'); wave.writeUInt32LE(40, 4); wave.write('WAVE', 8);
  await writeFile(path.join(files, 'fictional.wav'), wave);
  const app = createApp({ dataDir: path.join(directory, 'data'), seed: false, scheduler: false, computerInfo: { codexAvailable: false }, chooseDirectory: async () => files });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); await rm(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${app.server.address().port}/api`;
  const request = (url, body) => fetch(base + url, body === undefined ? {} : { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const connected = await request('/library/roots', { path: files, mode: 'copied' }); assert.equal(connected.status, 201); await app.library.settled();
  const listed = await (await request('/library/documents')).json(); assert.equal(listed.total, 2);
  const note = listed.items.find(item => item.name === 'note.md'), audio = listed.items.find(item => item.name.endsWith('.wav'));
  assert.equal((await request(`/library/documents/${note.id}?revision=unowned`)).status, 404);
  const hit = await (await request('/library/search?query=' + encodeURIComponent('周末'))).json(); assert.equal(hit.items[0].id, note.id);
  const filenameHit = await (await request('/library/search?query=fictional.wav')).json(); assert.equal(filenameHit.items[0].id, audio.id);
  const connector = await (await request('/connectors', { kind: 'library', name: 'Fictional library' })).json();
  const prepared = await app.connectors.prepare([connector.id]);
  const search = prepared.definitions.find(tool => tool.description.includes('/ search.')), read = prepared.definitions.find(tool => tool.description.includes('/ read.'));
  const result = await prepared.call({ tool: search.name, arguments: { queries: ['读书', '周末'] } }); assert.equal(result.success, true); assert.match(result.contentItems[0].text, /周末一起看书/);
  const context = await prepared.call({ tool: read.name, arguments: { id: note.id, revision: note.revision, offset: 0 } }); assert.equal(context.success, true); assert.match(context.contentItems[0].text, /untrusted_evidence/);
  const boot = await (await request('/bootstrap')).json(); assert.ok(!JSON.stringify(boot).includes('我们周末一起看书'));
  const snapshot = await (await request(`/library/documents/${note.id}/evidence`, { revision: note.revision, offset: 0 })).json();
  assert.match(snapshot.text, /周末一起看书/); assert.ok(snapshot.libraryEvidence.citations[0].includes(note.revision));
  assert.equal(app.store.list('facts').length, 0); assert.equal(app.store.list('tasks').length, 0);
  const sourceBefore = app.store.require('sources', snapshot.id);
  await writeFile(path.join(files, 'note.md'), '虚构材料：周末看书已取消。');
  app.library.action(listed.items[0].rootId, 'scan'); await app.library.settled();
  const evidence = evidenceFor(app.store, [{ sourceIds: [snapshot.id] }], { bounded: true });
  assert.equal(evidence.sources[0].libraryEvidence.state, 'newer_version');
  assert.deepEqual(app.store.require('sources', snapshot.id), sourceBefore);
  assert.equal((await (await request(`/library/documents/${note.id}/evidence`, { revision: note.revision })).json()).id, snapshot.id);
  const partial = await fetch(`${base}/library/documents/${audio.id}/original?inline=true`, { headers: { Range: 'bytes=0-3' } });
  assert.equal(partial.status, 206); assert.equal(partial.headers.get('content-type'), 'audio/wav'); assert.equal(await partial.text(), 'RIFF');
  assert.equal((await fetch(`${base}/library/documents/${audio.id}/original`, { headers: { Range: 'bytes=999-1000' } })).status, 416);
  await rm(path.join(files, 'note.md'));
  assert.match(await (await request(`/library/documents/${note.id}/original`)).text(), /周末看书已取消/);
});

test('saved attachment APIs index the tail in place and retain source and memory records', async t => {
  const directory = await realpath(await mkdtemp(path.join(os.tmpdir(), 'secondu-saved-http-')));
  const app = createApp({ dataDir: path.join(directory, 'data'), seed: false, scheduler: false, computerInfo: { codexAvailable: false } });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await app.close(); await rm(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${app.server.address().port}/api/library`;
  const attachment = saveAttachment(app.store, { name: 'fictional-history.txt', mime: 'text/plain', data: Buffer.from('虚构材料。\n'.repeat(7000) + '虚构尾部标记：金色企鹅约在周六读书。').toString('base64') });
  const source = app.store.put('sources', { id: 'source-fixture', title: '虚构历史索引', kind: 'document', text: '这是索引说明，正文在附件中。', attachmentIds: [attachment.id], createdAt: new Date().toISOString(), demo: false });
  const fact = app.store.put('facts', { id: 'fact-fixture', statement: '虚构既有确认记录', sourceIds: [source.id], status: 'confirmed' });
  const before = JSON.stringify({ sources: app.store.list('sources'), facts: app.store.list('facts'), attachments: app.store.list('attachments') });
  const status = await (await fetch(`${base}/existing-attachments/status`)).json();
  assert.equal(status.enabled, false); assert.equal(status.counts.total, 1);
  assert.equal((await (await fetch(`${base}/documents`)).json()).total, 0);
  const started = await fetch(`${base}/existing-attachments/scan`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(started.status, 202); await app.library.settled();
  const indexed = await (await fetch(`${base}/existing-attachments/status`)).json();
  assert.equal(indexed.counts.indexed, 1);
  const listed = await (await fetch(`${base}/existing-attachments?sourceId=${source.id}`)).json();
  assert.equal(listed.total, 1); assert.match(listed.items[0].documentId, /^document_/);
  assert.deepEqual((await (await fetch(`${base}/existing-attachments?sourceId=unrelated`)).json()).items, []);
  const found = await (await fetch(`${base}/search?query=${encodeURIComponent('金色企鹅')}`)).json();
  assert.equal(found.items[0].id, listed.items[0].documentId);
  const doc = listed.items[0].documentId;
  const original = await fetch(`${base}/documents/${doc}/original`);
  assert.equal(original.status, 200); assert.match(await original.text(), /金色企鹅/);
  const sourceAfter = app.store.require('sources', source.id); assert.deepEqual(sourceAfter, source);
  assert.deepEqual(app.store.require('facts', fact.id), fact);
  assert.equal(JSON.stringify({ sources: app.store.list('sources'), facts: app.store.list('facts'), attachments: app.store.list('attachments') }), before);
  assert.equal(app.store.list('tasks').length, 0);
  assert.ok(!JSON.stringify(indexed).includes(directory));
});
